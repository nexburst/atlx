#!/usr/bin/env bash
# Inventory of twg's command tree: command paths, positional args and long
# flag names only. Descriptions and help text are deliberately dropped: twg's
# help text is proprietary, while command and flag names are interface facts.
#
# Usage: scripts/twg-inventory.sh [path-to-twg]
#   Writes compat/twg-<version>.txt (or $TWG_INVENTORY_OUT). CI has no twg, so the maintainer runs
#   this locally after a twg upgrade and commits the result.
#
# Output format (sorted, one entry per line):
#   alias: <parent path> <alias> -> <canonical name>
#   group: <path> <--flag>...                 flags declared on a command group
#   <path> [<positional>...] [<--flag>...]    one line per leaf command
set -euo pipefail

TWG=${1:-${TWG:-twg}}
# Product trees plus the top-level account commands. TWG_ROOTS overrides.
# shellcheck disable=SC2206
ROOTS=(${TWG_ROOTS:-jira confluence bitbucket user jsm auth login logout whoami setup doctor})
version=$("$TWG" --version | tr -d '[:space:]')
here=$(cd "$(dirname "$0")/.." && pwd)
out=${TWG_INVENTORY_OUT:-"$here/compat/twg-$version.txt"}
mkdir -p "$(dirname "$out")"
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# Long flags of one help page, sorted and space-separated.
flags_of() {
  awk '
    /^Options:/ { inopt = 1; next }
    /^[^ ]/ { inopt = 0 }
    inopt && /^  -/ {
      # The flag spec ends at the first run of two or more spaces.
      spec = $0; sub(/^  /, "", spec); sub(/  .*/, "", spec)
      n = split(spec, parts, /[ ,]+/)
      for (i = 1; i <= n; i++)
        if (parts[i] ~ /^--[A-Za-z0-9]/ && parts[i] != "--help") print parts[i]
    }' | LC_ALL=C sort -u | tr '\n' ' ' | sed 's/ $//'
}

# Subcommands of one help page, one per line as "name [alias...]".
subs_of() {
  awk '
    /^Commands:/ { incmd = 1; next }
    /^[^ ]/ { incmd = 0 }
    incmd && /^  [a-z]/ {
      name = $1
      if (name == "help") next
      gsub(/\|/, " ", name)
      print name
    }'
}

# Positional args from the Usage line, without [options] and [command].
args_of() {
  awk -v path="$1" '
    /^Usage:/ {
      n = split($0, t, / +/)
      # t[1] is "Usage:", t[2] is "twg", then one word per path segment
      # (a segment may be printed as name|alias).
      skip = split(path, p, / /) + 2
      out = ""
      for (i = skip + 1; i <= n; i++) {
        if (t[i] == "[options]" || t[i] == "[command]") continue
        out = out (out == "" ? "" : " ") t[i]
      }
      print out
      exit
    }'
}

walk() {
  local path=$1 help subs args flags
  [[ -n ${VERBOSE:-} ]] && echo "$path" >&2
  # shellcheck disable=SC2086
  help=$("$TWG" $path --help 2>&1 || true)
  subs=$(printf '%s\n' "$help" | subs_of)
  flags=$(printf '%s\n' "$help" | flags_of)
  args=$(printf '%s\n' "$help" | args_of "$path")
  if [[ -z $subs ]]; then
    echo "$path${args:+ $args}${flags:+ $flags}" >>"$tmp"
    return
  fi
  if [[ -n $flags ]]; then echo "group: $path $flags" >>"$tmp"; fi
  # A group that also runs on its own (takes positionals) is a leaf too.
  if [[ -n $args ]]; then echo "$path $args${flags:+ $flags}" >>"$tmp"; fi
  local entry name al a
  while read -r entry; do
    [[ -z $entry ]] && continue
    read -r name al <<<"$entry"
    for a in $al; do echo "alias: $path $a -> $name" >>"$tmp"; done
    walk "$path $name"
  done <<<"$subs"
}

echo "alias: bb -> bitbucket" >>"$tmp"
for r in "${ROOTS[@]}"; do
  walk "$r"
done

{
  echo "# twg $version command inventory, generated by scripts/twg-inventory.sh."
  echo "# Command paths, positional args and long flag names only; no help text."
  LC_ALL=C sort -u "$tmp"
} >"$out"
echo "wrote $out ($(grep -vc '^\(#\|alias:\|group:\)' "$out") leaf commands)" >&2
